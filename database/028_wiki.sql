CREATE TABLE IF NOT EXISTS wiki_pages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 path VARCHAR(500) NOT NULL,
 path_key VARCHAR(500) NOT NULL,
 title VARCHAR(255) NOT NULL,
 body_text MEDIUMTEXT NOT NULL,
 html MEDIUMTEXT NOT NULL,
 render_version SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 content_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 file_mtime BIGINT NULL,
 file_size INT UNSIGNED NULL,
 current_revision_no INT UNSIGNED NOT NULL DEFAULT 0,
 created_by BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL,
 updated_by BIGINT UNSIGNED NULL,
 updated_at DATETIME NOT NULL,
 deleted_at DATETIME NULL,
 active_path_key VARCHAR(500) AS (IF(deleted_at IS NULL, path_key, NULL)) STORED,
 UNIQUE KEY wiki_pages_active_path (active_path_key),
 KEY wiki_pages_updated (deleted_at, updated_at),
 FULLTEXT KEY wiki_pages_search (title, body_text),
 FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
 FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS wiki_revisions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 page_id BIGINT UNSIGNED NOT NULL,
 revision_no INT UNSIGNED NOT NULL,
 action VARCHAR(16) NOT NULL,
 source VARCHAR(16) NOT NULL,
 path_before VARCHAR(500) NULL,
 path_after VARCHAR(500) NULL,
 content MEDIUMTEXT NOT NULL,
 content_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 lines_added INT UNSIGNED NOT NULL DEFAULT 0,
 lines_removed INT UNSIGNED NOT NULL DEFAULT 0,
 message VARCHAR(255) NULL,
 user_id BIGINT UNSIGNED NULL,
 user_name VARCHAR(190) NOT NULL,
 created_at DATETIME NOT NULL,
 UNIQUE KEY wiki_revisions_number (page_id, revision_no),
 KEY wiki_revisions_page_date (page_id, created_at),
 FOREIGN KEY (page_id) REFERENCES wiki_pages(id) ON DELETE CASCADE,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
