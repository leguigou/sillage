ALTER TABLE projects ADD require_ticket_validation BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE releases (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 project_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(120) NOT NULL,
 description TEXT NOT NULL,
 target_date DATE NULL,
 archived BOOLEAN NOT NULL DEFAULT FALSE,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(project_id,name),
 FOREIGN KEY(project_id) REFERENCES projects(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
ALTER TABLE tickets
 ADD release_id BIGINT UNSIGNED NULL,
 ADD resolution VARCHAR(24) NULL,
 ADD validation_state VARCHAR(12) NOT NULL DEFAULT 'pending',
 ADD validated_by BIGINT UNSIGNED NULL,
 ADD validated_at DATETIME NULL,
 ADD validation_note TEXT NULL,
 ADD FOREIGN KEY(release_id) REFERENCES releases(id),
 ADD FOREIGN KEY(validated_by) REFERENCES users(id);
UPDATE tickets SET resolution='completed' WHERE completed_at IS NOT NULL;
CREATE TABLE ticket_worklogs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 ticket_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 worked_on DATE NOT NULL,
 hours DECIMAL(6,2) NOT NULL,
 note VARCHAR(2000) NOT NULL,
 deleted BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(ticket_id,deleted,id),
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE ticket_history (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 ticket_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NULL,
 ticket_version INT NOT NULL,
 action VARCHAR(40) NOT NULL,
 source VARCHAR(24) NOT NULL,
 changes_json JSON NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(ticket_id,id),
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
 FOREIGN KEY(actor_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE release_deliveries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 release_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 environment VARCHAR(12) NOT NULL,
 outcome VARCHAR(12) NOT NULL,
 reference VARCHAR(240) NOT NULL,
 note VARCHAR(2000) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(release_id,id),
 FOREIGN KEY(release_id) REFERENCES releases(id),
 FOREIGN KEY(actor_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
