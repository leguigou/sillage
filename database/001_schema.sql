CREATE TABLE IF NOT EXISTS migrations (version VARCHAR(100) PRIMARY KEY, applied_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, email VARCHAR(190) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'member', verified_at DATETIME NULL,
 active TINYINT NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS auth_tokens (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, token_hash CHAR(64) NOT NULL UNIQUE,
 purpose VARCHAR(20) NOT NULL, expires_at DATETIME NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rate_limits (bucket CHAR(64) PRIMARY KEY, hits INT NOT NULL, expires_at BIGINT NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS projects (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, project_key VARCHAR(12) NOT NULL UNIQUE,
 description TEXT, color VARCHAR(20) NOT NULL DEFAULT '#7166eb', next_number INT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS tickets (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, project_id BIGINT UNSIGNED NOT NULL, number INT NOT NULL,
 title VARCHAR(240) NOT NULL, description MEDIUMTEXT NOT NULL, type VARCHAR(20) NOT NULL DEFAULT 'task',
 status VARCHAR(20) NOT NULL DEFAULT 'todo', priority VARCHAR(20) NOT NULL DEFAULT 'medium',
 assignee_id BIGINT UNSIGNED NULL, reporter_id BIGINT UNSIGNED NULL, parent_id BIGINT UNSIGNED NULL,
 labels JSON NOT NULL, start_date DATE NULL, due_date DATE NULL, rank_value DECIMAL(18,4) NOT NULL DEFAULT 0,
 flagged TINYINT NOT NULL DEFAULT 0, archived TINYINT NOT NULL DEFAULT 0, external_email VARCHAR(190) NULL,
 version INT NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, completed_at DATETIME NULL,
 UNIQUE(project_id,number), INDEX(project_id,status,archived), INDEX(project_id,due_date), INDEX(parent_id),
 FOREIGN KEY(project_id) REFERENCES projects(id), FOREIGN KEY(assignee_id) REFERENCES users(id),
 FOREIGN KEY(reporter_id) REFERENCES users(id), FOREIGN KEY(parent_id) REFERENCES tickets(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS comments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ticket_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 body TEXT NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE, FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS activity (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, project_id BIGINT UNSIGNED NOT NULL, ticket_id BIGINT UNSIGNED NULL,
 user_id BIGINT UNSIGNED NULL, message VARCHAR(500) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(project_id,created_at), FOREIGN KEY(project_id) REFERENCES projects(id),
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE SET NULL, FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS attachments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ticket_id BIGINT UNSIGNED NOT NULL, original_name VARCHAR(240) NOT NULL,
 stored_name CHAR(64) NOT NULL UNIQUE, mime VARCHAR(120) NOT NULL, size_bytes BIGINT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ticket_links (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, source_id BIGINT UNSIGNED NOT NULL, target_id BIGINT UNSIGNED NOT NULL,
 relation VARCHAR(30) NOT NULL, UNIQUE(source_id,target_id,relation),
 FOREIGN KEY(source_id) REFERENCES tickets(id) ON DELETE CASCADE, FOREIGN KEY(target_id) REFERENCES tickets(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS saved_views (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, project_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(120) NOT NULL, settings JSON NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY(project_id) REFERENCES projects(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS formatting_rules (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, project_id BIGINT UNSIGNED NOT NULL, field VARCHAR(30) NOT NULL,
 match_value VARCHAR(120) NOT NULL, color VARCHAR(20) NOT NULL, title VARCHAR(120) NOT NULL,
 FOREIGN KEY(project_id) REFERENCES projects(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS public_forms (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, project_id BIGINT UNSIGNED NOT NULL, title VARCHAR(160) NOT NULL,
 description TEXT NOT NULL, token_hash CHAR(64) NOT NULL UNIQUE, fields_json JSON NOT NULL,
 ticket_type VARCHAR(20) NOT NULL DEFAULT 'task', enabled TINYINT NOT NULL DEFAULT 1,
 reporter_id BIGINT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(project_id) REFERENCES projects(id), FOREIGN KEY(reporter_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS connections (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, project_id BIGINT UNSIGNED NOT NULL,
 provider VARCHAR(20) NOT NULL, repository VARCHAR(200) NOT NULL, secret_cipher TEXT NOT NULL,
 webhook_cipher TEXT NOT NULL, last_sync_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(project_id,provider,repository), FOREIGN KEY(project_id) REFERENCES projects(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS development_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, connection_id BIGINT UNSIGNED NOT NULL, ticket_id BIGINT UNSIGNED NULL,
 external_key VARCHAR(190) NOT NULL, kind VARCHAR(30) NOT NULL, title VARCHAR(500) NOT NULL,
 external_url VARCHAR(1000) NULL, state VARCHAR(60) NOT NULL, occurred_at DATETIME NOT NULL,
 UNIQUE(connection_id,external_key), FOREIGN KEY(connection_id) REFERENCES connections(id) ON DELETE CASCADE,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
