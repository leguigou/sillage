CREATE TABLE IF NOT EXISTS mcp_tokens (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(120) NOT NULL, token_hash CHAR(64) NOT NULL UNIQUE, fingerprint CHAR(12) NOT NULL,
 scopes JSON NOT NULL, auth_version INT NOT NULL, expires_at DATETIME NULL,
 last_used_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(user_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mcp_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, token_id BIGINT UNSIGNED NULL,
 user_id BIGINT UNSIGNED NOT NULL, tool_name VARCHAR(100) NOT NULL, succeeded TINYINT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX(user_id,id),
 FOREIGN KEY(token_id) REFERENCES mcp_tokens(id) ON DELETE SET NULL,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS automation_rules (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, project_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(120) NOT NULL, trigger_event VARCHAR(40) NOT NULL, conditions_json JSON NOT NULL,
 actions_json JSON NOT NULL, enabled TINYINT NOT NULL DEFAULT 1, version INT NOT NULL DEFAULT 1,
 created_by BIGINT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(project_id) REFERENCES projects(id), FOREIGN KEY(created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS automation_runs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, rule_id BIGINT UNSIGNED NULL,
 ticket_id BIGINT UNSIGNED NOT NULL, rule_name VARCHAR(120) NOT NULL, event_name VARCHAR(40) NOT NULL,
 succeeded TINYINT NOT NULL, message VARCHAR(500) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(ticket_id,id), FOREIGN KEY(rule_id) REFERENCES automation_rules(id) ON DELETE SET NULL,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
