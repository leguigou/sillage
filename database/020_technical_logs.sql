CREATE TABLE IF NOT EXISTS technical_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 request_id CHAR(32) NOT NULL,
 direction VARCHAR(8) NOT NULL,
 channel VARCHAR(16) NOT NULL,
 provider VARCHAR(24) NOT NULL DEFAULT '',
 method VARCHAR(12) NOT NULL,
 endpoint VARCHAR(600) NOT NULL,
 operation VARCHAR(100) NOT NULL DEFAULT '',
 outcome VARCHAR(8) NOT NULL,
 http_status SMALLINT UNSIGNED NULL,
 duration_ms INT UNSIGNED NOT NULL,
 request_bytes BIGINT UNSIGNED NULL,
 response_bytes BIGINT UNSIGNED NULL,
 user_id BIGINT UNSIGNED NULL,
 token_id BIGINT UNSIGNED NULL,
 connection_id BIGINT UNSIGNED NULL,
 error_code VARCHAR(64) NOT NULL DEFAULT '',
 INDEX technical_created (created_at,id),
 INDEX technical_correlation (request_id,id),
 INDEX technical_channel (channel,created_at,id),
 INDEX technical_provider (provider,created_at,id),
 INDEX technical_outcome (outcome,created_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
