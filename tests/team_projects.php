<?php
use App\Models\{Team,Project,Ticket};
use App\Services\{Query,Filter};
use App\Core\DB;

$teamA=Team::save(null,'Développement '.bin2hex(random_bytes(4)));
$teamB=Team::save(null,'Support '.bin2hex(random_bytes(4)));
$pa=Project::save(['name'=>'Projet équipes A','key'=>'TA'.strtoupper(bin2hex(random_bytes(3))),'team_ids'=>[$teamA,$teamB]]);
$pb=Project::save(['name'=>'Projet équipes B','key'=>'TB'.strtoupper(bin2hex(random_bytes(3))),'team_ids'=>[$teamA]]);
check(count(Team::forProject($pa))===2 && count(Team::forProject($pb))===1,'plusieurs équipes par projet et plusieurs projets par équipe');
Team::projectMembership($teamA,$pa,true);
check(count(Team::forProject($pa))===2,'association équipe projet idempotente');
Team::membership($teamA,$uid,true); Team::membership($teamB,$uid,true);
check((int)DB::one('SELECT COUNT(*) n FROM team_members WHERE user_id=? AND team_id IN (?,?)',[$uid,$teamA,$teamB])['n']===2,'même collaborateur membre de plusieurs équipes');
$ta=Ticket::create($pa,['title'=>'Responsabilités distinctes','team_id'=>$teamA,'assignee_id'=>$uid,'progress_percent'=>40,'estimated_hours'=>'2.5'],$uid);
$tb=Ticket::create($pb,['title'=>'Autre projet','team_id'=>$teamA],$uid);
$unassigned=Ticket::create($pa,['title'=>'Sans équipe'],$uid);
check(Ticket::find($ta)['team_id']===$teamA && Ticket::find($ta)['assignee_id']===$uid,'équipe responsable et personne assignée conservées ensemble');
rejects(fn()=>Ticket::create($pb,['title'=>'Mauvaise équipe','team_id'=>$teamB],$uid),'affectation à une équipe étrangère au projet refusée');
foreach(['invalid',0,-1,[],true] as $badTeam) rejects(fn()=>Ticket::validate(['title'=>'Test','team_id'=>$badTeam],$pa),'identifiant équipe invalide refusé');
check(Query::count(0,['team'=>$teamA])===2 && Query::count($pa,['team'=>'none'])===1,'filtres équipe et sans équipe sur plusieurs projets');
check(Filter::active(['team'=>$teamA]) && !Filter::active(['team'=>'']),'réinitialisation uniquement pour un filtre équipe actif');
check(Query::count($pa,['jql'=>'team = "'.Team::find($teamA)['name'].'"'])===1,'requête avancée par nom d’équipe');
$work=Query::teamWorkload($pa,['team'=>$teamA])[0];
check((int)$work['total']===1 && (float)$work['progress']===40.0 && (float)$work['hours']===2.5,'rapport équipe agrège avancement et heures sur tous les tickets filtrés');
rejects(fn()=>Team::projectMembership($teamA,$pa,false),'retrait équipe projet avec tickets affectés refusé');
rejects(fn()=>Project::save(['name'=>'Modification à annuler','team_ids'=>[$teamB]],$pa),'modification projet sans réaffectation des tickets refusée');
check(Project::find($pa)['name']==='Projet équipes A' && count(Team::forProject($pa))===2,'échec de retrait annule toute la modification du projet');
$before=Ticket::find($ta);
Ticket::patch($ta,['priority'=>'high'],$uid,$before['version']);
check(Ticket::find($ta)['team_id']===$teamA,'modification partielle conserve l’équipe');
Ticket::patch($ta,['team_id'=>null],$uid,Ticket::find($ta)['version']);
check(Ticket::find($ta)['assignee_id']===$uid && Ticket::find($ta)['team_id']===null,'retrait équipe conserve le responsable individuel');
Team::projectMembership($teamA,$pa,false);
check(count(Team::forProject($pa))===1 && count(Team::forProject($pb))===1,'retrait après réaffectation préserve les autres projets');
Ticket::archive($tb,true,$uid,Ticket::find($tb)['version']);
rejects(fn()=>Team::projectMembership($teamA,$pb,false),'tickets archivés empêchent aussi la suppression du lien projet');
$old=Ticket::find($tb);Team::delete($teamA);$after=Ticket::find($tb);
check($after['team_id']===null && $after['archived'] && $after['version']===$old['version']+1 && DB::one('SELECT id FROM users WHERE id=?',[$uid]),'suppression équipe conserve tickets archivés et comptes et invalide les éditions anciennes');
rejects(fn()=>Ticket::patch($tb,['title'=>'Ancienne version'],$uid,$old['version']),'ancienne édition après suppression équipe refusée');
